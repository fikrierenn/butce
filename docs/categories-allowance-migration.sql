-- 6. KATEGORİLERİ HİYERARŞİK OLARAK GETİREN FONKSİYON
CREATE OR REPLACE FUNCTION public.get_categories_hierarchical()
RETURNS TABLE (
    id bigint,
    user_id uuid,
    name text,
    type text,
    parent_id bigint,
    subcategories jsonb
) AS $$
BEGIN
    RETURN QUERY
    WITH RECURSIVE category_tree AS (
        -- Ana kategoriler (parent_id NULL olanlar)
        SELECT 
            c.id,
            c.user_id,
            c.name,
            c.type,
            c.parent_id,
            '[]'::jsonb as subcategories
        FROM public.but_categories c
        WHERE c.user_id = auth.uid() AND c.parent_id IS NULL
        
        UNION ALL
        
        -- Alt kategoriler
        SELECT 
            c.id,
            c.user_id,
            c.name,
            c.type,
            c.parent_id,
            '[]'::jsonb as subcategories
        FROM public.but_categories c
        INNER JOIN category_tree ct ON c.parent_id = ct.id
        WHERE c.user_id = auth.uid()
    )
    SELECT 
        ct.id,
        ct.user_id,
        ct.name,
        ct.type,
        ct.parent_id,
        (
            SELECT jsonb_agg(
                jsonb_build_object(
                    'id', sub.id,
                    'name', sub.name,
                    'type', sub.type,
                    'parent_id', sub.parent_id
                )
            )
            FROM public.but_categories sub
            WHERE sub.parent_id = ct.id AND sub.user_id = auth.uid()
        ) as subcategories
    FROM category_tree ct
    WHERE ct.parent_id IS NULL
    ORDER BY ct.type, ct.name;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Fonksiyon için RLS politikası
GRANT EXECUTE ON FUNCTION public.get_categories_hierarchical() TO authenticated;
