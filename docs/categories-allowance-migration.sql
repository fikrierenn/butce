-- 1. KATEGORİ TABLOSU (eğer yoksa oluştur)
CREATE TABLE IF NOT EXISTS public.but_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name text NOT NULL,
    type text NOT NULL CHECK (type IN ('income', 'expense', 'allowance')),
    parent_id bigint REFERENCES public.but_categories(id) ON DELETE CASCADE,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now(),
    
    -- Benzersizlik: Aynı kullanıcı aynı isimde kategori oluşturamaz
    UNIQUE(user_id, name)
);

-- 2. ROW LEVEL SECURITY
ALTER TABLE public.but_categories ENABLE ROW LEVEL SECURITY;

-- Kullanıcılar sadece kendi kategorilerini görebilir
CREATE POLICY "Users can view their own categories"
    ON public.but_categories
    FOR SELECT
    USING (auth.uid() = user_id);

-- Kullanıcılar kendi kategorilerini oluşturabilir
CREATE POLICY "Users can create their own categories"
    ON public.but_categories
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

-- Kullanıcılar kendi kategorilerini güncelleyebilir
CREATE POLICY "Users can update their own categories"
    ON public.but_categories
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Kullanıcılar kendi kategorilerini silebilir
CREATE POLICY "Users can delete their own categories"
    ON public.but_categories
    FOR DELETE
    USING (auth.uid() = user_id);

-- 3. İNDEXLER (performans için)
CREATE INDEX IF NOT EXISTS idx_but_categories_user_id ON public.but_categories(user_id);
CREATE INDEX IF NOT EXISTS idx_but_categories_type ON public.but_categories(type);
CREATE INDEX IF NOT EXISTS idx_but_categories_parent_id ON public.but_categories(parent_id);

-- 4. TRIGGER: updated_at otomatik güncelleme
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER update_but_categories_updated_at 
    BEFORE UPDATE ON public.but_categories 
    FOR EACH ROW 
    EXECUTE FUNCTION public.update_updated_at_column();

