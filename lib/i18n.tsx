// ── Locale mapping for Intl ──────────────────────────────────────────
const LOCALE_MAP: Record<string, string> = {
  tr: 'tr-TR',
  en: 'en-US',
  de: 'de-DE',
  fr: 'fr-FR',
  es: 'es-ES',
  ar: 'ar-SA',
  ru: 'ru-RU',
  ja: 'ja-JP',
  zh: 'zh-CN',
  pt: 'pt-BR',
};

// ── Context ──────────────────────────────────────────────────────────
interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  t: (key: string) => string;
  formatCurrency: (amount: number) => string;
  formatDate: (dateString: string) => string;
  currency: string;
  setCurrency: (currency: string) => void;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

// ── Helper: detect browser language ──────────────────────────────────
function detectBrowserLanguage(): string {
  try {
    const browserLang = navigator.language?.split('-')[0] ?? 'tr';
    const supported = SUPPORTED_LANGUAGES.map((l) => l.code);
    return supported.includes(browserLang) ? browserLang : 'tr';
  } catch {
    return 'tr';
  }
}

// ── Provider ─────────────────────────────────────────────────────────
export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<string>(() => {
    try {
      const saved = localStorage.getItem('spendme-language');
      if (saved && translations[saved]) return saved;
    } catch {}
    // Dil seçici kapalı olduğu için her zaman Türkçe
    return 'tr';
  });

  const [currency, setCurrencyState] = useState<string>(() => {
    try {
      const saved = localStorage.getItem('spendme-currency');
      if (saved) return saved;
    } catch {}
    return DEFAULT_CURRENCY_MAP[detectBrowserLanguage()] || 'TRY';
  });

  const setLanguage = useCallback((lang: string) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('spendme-language', lang);
    } catch {}
  }, []);

  const setCurrency = useCallback((cur: string) => {
    setCurrencyState(cur);
    try {
      localStorage.setItem('spendme-currency', cur);
    } catch {}
  }, []);

  const t = useCallback(
    (key: string): string => {
      // Current language
      if (translations[language]?.[key]) return translations[language][key];
      // Fallback to Turkish
      if (translations.tr?.[key]) return translations.tr[key];
      // Return key itself
      return key;
    },
    [language],
  );

  const formatCurrency = useCallback(
    (amount: number): string => {
      try {
        return new Intl.NumberFormat(LOCALE_MAP[language] || 'tr-TR', {
          style: 'currency',
          currency: currency,
          minimumFractionDigits: 2,
          maximumFractionDigits: 2,
        }).format(amount);
      } catch {
        return `${amount.toFixed(2)} ${currency}`;
      }
    },
    [language, currency],
  );

  const formatDate = useCallback(
    (dateString: string): string => {
      try {
        const date = new Date(dateString);
        return new Intl.DateTimeFormat(LOCALE_MAP[language] || 'tr-TR', {
          year: 'numeric',
          month: 'long',
          day: 'numeric',
        }).format(date);
      } catch {
        return dateString;
      }
    },
    [language],
  );

  const value: LanguageContextType = {
    language,
    setLanguage,
    t,
    formatCurrency,
    formatDate,
    currency,
    setCurrency,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

// ── Hook ─────────────────────────────────────────────────────────────
export function useI18n(): LanguageContextType {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useI18n must be used within a LanguageProvider');
  }
  return context;
}
